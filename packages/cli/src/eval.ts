// `tracepilot eval [--scenario <name>]... [--seed <n>]... [--investigator auto|scripted|cassette|live]
//                  [--json] [--write-readme]`
//
// Simulates each scenario, investigates it, scores the result against eval/ground-truth/ and
// replays the recommended patch (brief §10). `auto` uses a recorded live run (eval/cassettes/) when
// one exists and otherwise the scripted fixture, and then lists the real-model run as not run.
// `--write-readme` puts the table into README.md between the eval markers.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import {
  evaluateScenario,
  hasRecordedRun,
  resultsTable,
  type EvalResult,
  type InvestigatorChoice,
  type NotRun,
} from '@tracepilot/eval';
import { SCENARIOS } from '@tracepilot/sim';
import { EXIT } from './exit.ts';

export interface Io {
  out: (line: string) => void;
  err: (line: string) => void;
}

export const README = fileURLToPath(new URL('../../../README.md', import.meta.url));
const GROUND_TRUTH = (s: string): string =>
  fileURLToPath(new URL(`../../../eval/ground-truth/${s}.json`, import.meta.url));
export const EVAL_START = '<!-- eval:start (generated by `tracepilot eval --write-readme`) -->';
export const EVAL_END = '<!-- eval:end -->';

/** Scenarios that have both a simulator recording factory and a ground-truth file. */
export const evalScenarios = (): string[] =>
  Object.keys(SCENARIOS).filter((s) => existsSync(GROUND_TRUTH(s)));

export function replaceBetweenMarkers(text: string, body: string): string {
  const start = text.indexOf(EVAL_START);
  const end = text.indexOf(EVAL_END);
  if (start < 0 || end < start)
    throw new Error(`README.md has no ${EVAL_START} … ${EVAL_END} section`);
  return `${text.slice(0, start + EVAL_START.length)}\n\n${body}\n\n${text.slice(end)}`;
}

export async function evalCommand(args: string[], io: Io): Promise<number> {
  const { values } = parseArgs({
    args,
    options: {
      scenario: { type: 'string', multiple: true },
      seed: { type: 'string', multiple: true },
      investigator: { type: 'string', default: 'auto' },
      json: { type: 'boolean', default: false },
      'write-readme': { type: 'boolean', default: false },
    },
  });
  const all = evalScenarios();
  const scenarios = values.scenario ?? all;
  const unknown = scenarios.filter((s) => !all.includes(s));
  if (unknown.length > 0) {
    io.err(
      `eval: no scenario with ground truth named ${unknown.join(', ')} (have: ${all.join(', ')})`,
    );
    return EXIT.usage;
  }
  if (!['auto', 'scripted', 'cassette', 'live'].includes(values.investigator)) {
    io.err('eval: --investigator must be auto, scripted, cassette or live');
    return EXIT.usage;
  }
  const seeds = (values.seed ?? ['42']).map(Number);
  if (seeds.some((s) => !Number.isSafeInteger(s) || s < 0)) {
    io.err('eval: --seed must be a non-negative integer');
    return EXIT.usage;
  }

  const rows: (EvalResult | NotRun)[] = [];
  for (const scenario of scenarios) {
    for (const seed of seeds) {
      const recorded = hasRecordedRun(scenario, seed);
      if (values.investigator === 'cassette' && !recorded) {
        rows.push({
          scenario,
          seed,
          investigator: 'model (recorded)',
          reason: 'no recorded cassette',
        });
        continue;
      }
      io.err(`eval: ${scenario} seed ${String(seed)}…`);
      rows.push(
        await evaluateScenario({
          scenario,
          seed,
          investigator: values.investigator as InvestigatorChoice,
        }),
      );
      if (values.investigator === 'auto' && !recorded)
        rows.push({
          scenario,
          seed,
          investigator: 'model (recorded)',
          reason: 'no recorded cassette yet (needs an API key; NOTES.md, Phase 3)',
        });
    }
  }
  const table = resultsTable(rows);
  if (values.json) io.out(JSON.stringify(rows, null, 1));
  else io.out(table);
  if (values['write-readme']) {
    writeFileSync(README, replaceBetweenMarkers(readFileSync(README, 'utf8'), table));
    io.err(`eval: table written to ${README}`);
  }
  const results = rows.filter((r): r is EvalResult => !('reason' in r));
  return results.every((r) => r.pass) ? EXIT.ok : EXIT.failed;
}
