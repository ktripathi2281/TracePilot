import { z } from 'zod';
import { EvidenceId, HypothesisId, LedgerEntryId, PredictionId } from './ids.ts';
import { FindingValue, LedgerAuthor } from './ledger.ts';

// Hypotheses with discriminating, testable predictions (brief §6).
//
// A prediction is not prose to be judged: it names a FINDING of a deterministic tool call and the
// value the hypothesis expects there. The engine runs the tool and compares. Scores come from
// those results, never from LLM self-reported confidence, so there is no confidence field here.

/**
 * What kind of explanation a hypothesis is. Used by the engine's coverage rules (e.g. a saturated
 * connection pool must be explained three competing ways) and carried into the diagnosis.
 */
export const HypothesisKind = z.enum([
  /** The pool is too small for legitimate demand: its connections are busy executing queries. */
  'pool_capacity',
  /** Connections are held idle by callers that wait for further connections from the same pool. */
  'hold_and_wait',
  /** The database executes queries more slowly. */
  'db_slow',
  /** A downstream service or external dependency is slow or failing. */
  'downstream_slow',
  /** A service ran out of workers for reasons of its own. */
  'worker_exhaustion',
  /** More or different traffic arrived. */
  'traffic_surge',
  /** A specific change event caused it by a mechanism not covered above. */
  'change_regression',
  'other',
]);
export type HypothesisKind = z.infer<typeof HypothesisKind>;

export const PredictionCheck = z.strictObject({
  /** Deterministic data tool to run. */
  tool: z.string().min(1),
  args: z.record(z.string(), z.unknown()),
  /** Key of the finding in that tool's output. */
  findingKey: z.string().min(1),
  /** `is`: the finding's value equals `expected`. `is_not`: it has a decided value different from it. */
  op: z.enum(['is', 'is_not']),
  expected: z.union([z.string(), z.number(), z.boolean()]),
});
export type PredictionCheck = z.infer<typeof PredictionCheck>;

export const PredictionResult = z.enum(['pending', 'supported', 'contradicted', 'inconclusive']);
export type PredictionResult = z.infer<typeof PredictionResult>;

export const Prediction = z
  .strictObject({
    id: PredictionId,
    statement: z.string().min(1),
    check: PredictionCheck,
    result: PredictionResult,
    /** The finding's value when the check ran; null if the finding was absent. */
    observed: FindingValue,
    /** Why the result is what it is, generated by the engine. */
    note: z.string(),
    evidenceIds: z.array(EvidenceId),
    /** The FACT entry holding the tested finding. */
    ledgerEntryIds: z.array(LedgerEntryId),
  })
  .refine(
    (p) => (p.result !== 'supported' && p.result !== 'contradicted') || p.evidenceIds.length > 0,
    { message: 'a supported/contradicted prediction must cite evidence', path: ['evidenceIds'] },
  );
export type Prediction = z.infer<typeof Prediction>;

export const HypothesisStatus = z.enum(['proposed', 'supported', 'rejected', 'inconclusive']);
export type HypothesisStatus = z.infer<typeof HypothesisStatus>;

export const Hypothesis = z.strictObject({
  id: HypothesisId,
  kind: HypothesisKind,
  proposedBy: LedgerAuthor,
  title: z.string().min(1),
  statement: z.string().min(1),
  predictions: z.array(Prediction).min(1),
  status: HypothesisStatus,
  /** The HYPOTHESIS ledger entry for this hypothesis. */
  ledgerEntryId: LedgerEntryId,
});
export type Hypothesis = z.infer<typeof Hypothesis>;
