import { useEffect, useState } from 'react';
import { api } from './api.ts';
import { fmtCount, fmtDur } from './format.ts';
import { ErrorLine, Loading, cx, useLoad } from './ui/parts.tsx';
import { IncidentView } from './views/Incident.tsx';
import { InvestigationView } from './views/Investigation.tsx';
import { OverviewView } from './views/Overview.tsx';
import { ReplayLab } from './views/ReplayLab.tsx';

export type ViewName = 'overview' | 'incident' | 'investigation' | 'replay';
const VIEWS: { name: ViewName; label: string }[] = [
  { name: 'overview', label: 'Overview' },
  { name: 'incident', label: 'Incident' },
  { name: 'investigation', label: 'Investigation' },
  { name: 'replay', label: 'Replay lab' },
];

/** `#/<view>/<incidentId>[?k=v...]` */
export interface Route {
  view: ViewName;
  incident: string | null;
  params: URLSearchParams;
}

function parseHash(hash: string): Route {
  const [path = '', query = ''] = hash.replace(/^#\/?/, '').split('?');
  const [view, incident] = path.split('/');
  const name = VIEWS.find((v) => v.name === view)?.name ?? 'overview';
  return { view: name, incident: incident ?? null, params: new URLSearchParams(query) };
}

export function href(
  view: ViewName,
  incident: string,
  params: Record<string, string> = {},
): string {
  const q = new URLSearchParams(params).toString();
  return `#/${view}/${incident}${q === '' ? '' : `?${q}`}`;
}

export function navigate(
  view: ViewName,
  incident: string,
  params: Record<string, string> = {},
): void {
  window.location.hash = href(view, incident, params);
}

export function App() {
  const [route, setRoute] = useState<Route>(() => parseHash(window.location.hash));
  useEffect(() => {
    const on = (): void => {
      setRoute(parseHash(window.location.hash));
    };
    window.addEventListener('hashchange', on);
    return () => {
      window.removeEventListener('hashchange', on);
    };
  }, []);
  const incidents = useLoad(() => api.incidents(), []);
  const incident = route.incident ?? incidents.data?.[0]?.id ?? null;

  return (
    <div className="flex h-full flex-col">
      <header className="flex flex-wrap items-center gap-x-6 gap-y-2 border-b border-zinc-800 px-5 py-2.5">
        <div className="font-mono text-[13px] font-semibold tracking-tight text-zinc-100">
          TracePilot
        </div>
        <nav className="flex gap-1" aria-label="views">
          {VIEWS.map((v) => (
            <a
              key={v.name}
              href={incident === null ? '#' : href(v.name, incident)}
              data-testid={`nav-${v.name}`}
              className={cx(
                'whitespace-nowrap rounded px-2.5 py-1 text-[12px]',
                route.view === v.name
                  ? 'bg-zinc-800 text-zinc-100'
                  : 'text-zinc-400 hover:text-zinc-200',
              )}
            >
              {v.label}
            </a>
          ))}
        </nav>
        <div className="ml-auto flex items-center gap-3 font-mono text-[11px] text-zinc-500">
          {incident !== null && (
            <label className="flex items-center gap-2">
              <span>incident</span>
              <select
                value={incident}
                onChange={(e) => {
                  navigate(route.view, e.target.value);
                }}
                data-testid="incident-select"
                className="max-w-[320px] rounded border border-zinc-700 bg-zinc-950 px-1.5 py-0.5 font-mono text-[11px] text-zinc-200"
              >
                {(incidents.data ?? []).map((i) => (
                  <option key={i.id} value={i.id}>
                    {i.id}
                    {` · p99 ${fmtDur(i.headline.p99Us)}, ${fmtCount(i.headline.failures)} failed`}
                  </option>
                ))}
              </select>
            </label>
          )}
          <span
            className="rounded bg-zinc-800 px-1.5 py-0.5 text-zinc-400"
            title="Telemetry generated by the TracePilot simulator"
          >
            synthetic telemetry
          </span>
        </div>
      </header>
      <main className="flex-1 overflow-auto px-5 py-4">
        {incidents.error !== null && <ErrorLine error={incidents.error} />}
        {incidents.loading && <Loading what="incidents" />}
        {incidents.data !== null && incident === null && (
          <div className="p-6 text-zinc-500">
            No incidents in the store. Run `tracepilot sim run` first.
          </div>
        )}
        {incident !== null && route.view === 'overview' && (
          <OverviewView incident={incident} incidents={incidents.data ?? []} />
        )}
        {incident !== null && route.view === 'incident' && (
          <IncidentView incident={incident} params={route.params} />
        )}
        {incident !== null && route.view === 'investigation' && (
          <InvestigationView incident={incident} />
        )}
        {incident !== null && route.view === 'replay' && (
          <ReplayLab incident={incident} params={route.params} />
        )}
      </main>
    </div>
  );
}
